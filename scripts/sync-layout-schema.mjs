// Copy the ONE layout schema (front/src/graphics/schema/layoutSchema.js) into
// the backend as Render_hosted/test-back/utils/layoutSchema.generated.cjs.
// The two deploy separately (Vercel / Render), so the backend carries a
// verbatim, hash-stamped copy — same "front is the source, backend gets a
// generated artifact" pattern as desktop-app/relay/build-sdk.mjs.
//
//   node scripts/sync-layout-schema.mjs          write the copy
//   node scripts/sync-layout-schema.mjs --check  exit 1 if the copy drifted

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const frontDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(frontDir, 'src', 'graphics', 'schema', 'layoutSchema.js');
const out = resolve(frontDir, '..', 'Render_hosted', 'test-back', 'utils', 'layoutSchema.generated.cjs');

const body = readFileSync(src, 'utf8');
const hash = createHash('sha256').update(body).digest('hex').slice(0, 16);
const generated = `// GENERATED by front/scripts/sync-layout-schema.mjs — DO NOT EDIT.\n// source: front/src/graphics/schema/layoutSchema.js  sha256:${hash}\n${body}`;

if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== generated) {
    console.error(`[layout-schema] ${out} is out of date — run: node front/scripts/sync-layout-schema.mjs`);
    process.exit(1);
  }
  console.log(`[layout-schema] in sync (sha256:${hash})`);
} else {
  writeFileSync(out, generated);
  console.log(`[layout-schema] wrote ${out} (sha256:${hash})`);
}
